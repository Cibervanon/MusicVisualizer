def default_style() -> dict[str, Any]:
    return dict(TEXT_PRESETS["minimal_white"])


def get_preset(preset_id: str) -> dict[str, Any]:
    return dict(TEXT_PRESETS.get(preset_id, TEXT_PRESETS["minimal_white"]))


def merge_style(preset_id: str | None, overrides: dict[str, Any] | None) -> dict[str, Any]:
    style = get_preset(preset_id or "minimal_white")
    for key, value in (overrides or {}).items():
        if value is not None:
            style[key] = value
    if style.get("animation_in") not in ANIMATIONS:
        style["animation_in"] = "fade"
    if style.get("animation_out") not in ANIMATIONS:
        style["animation_out"] = "fade"
    return style


def preset_catalog() -> list[dict[str, Any]]:
    return list(TEXT_PRESETS.values())
